/**
 * scripts/sync-google-sheets.js
 * Synchronizes stationery products & services pricing from a Google Sheet (CSV export)
 * directly into src/data/productsData.js and src/data/servicesData.js.
 */

import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const projectRoot = path.resolve(__dirname, '..');

// Simple, robust RFC 4180 CSV parser
function parseCSV(text) {
  const lines = [];
  let currentRow = [];
  let currentCell = '';
  let insideQuotes = false;

  for (let i = 0; i < text.length; i++) {
    const char = text[i];
    const nextChar = text[i + 1];

    if (char === '"') {
      if (insideQuotes && nextChar === '"') {
        currentCell += '"';
        i++;
      } else {
        insideQuotes = !insideQuotes;
      }
    } else if (char === ',' && !insideQuotes) {
      currentRow.push(currentCell.trim());
      currentCell = '';
    } else if ((char === '\r' || char === '\n') && !insideQuotes) {
      if (char === '\r' && nextChar === '\n') {
        i++;
      }
      currentRow.push(currentCell.trim());
      if (currentRow.some((c) => c.length > 0)) {
        lines.push(currentRow);
      }
      currentRow = [];
      currentCell = '';
    } else {
      currentCell += char;
    }
  }

  if (currentCell.length > 0 || currentRow.length > 0) {
    currentRow.push(currentCell.trim());
    if (currentRow.some((c) => c.length > 0)) {
      lines.push(currentRow);
    }
  }

  if (lines.length < 2) return [];

  const headers = lines[0].map((h) => h.toLowerCase().replace(/[^a-z0-9]/g, ''));
  const data = [];

  for (let i = 1; i < lines.length; i++) {
    const row = lines[i];
    const obj = {};
    headers.forEach((header, idx) => {
      obj[header] = row[idx] || '';
    });
    data.push(obj);
  }

  return data;
}

export async function syncGoogleSheets() {
  const configPath = path.join(projectRoot, 'config', 'automation.json');
  let config = {};
  try {
    const raw = await fs.readFile(configPath, 'utf-8');
    config = JSON.parse(raw);
  } catch {
    console.warn('[Google Sheets Sync] Could not read config/automation.json, using environment defaults.');
  }

  const spreadsheetId = process.env.GOOGLE_SPREADSHEET_ID || config.googleSheets?.spreadsheetId;
  const productsSheetName = config.googleSheets?.productsSheetName || 'Products';
  const servicesSheetName = config.googleSheets?.servicesSheetName || 'Services';

  if (!spreadsheetId) {
    console.log('[Google Sheets Sync] (Info) No GOOGLE_SPREADSHEET_ID configured in config/automation.json or .env.');
    console.log('[Google Sheets Sync] (Info) To enable live phone editing: add spreadsheetId to config/automation.json.');
    return { synced: false, reason: 'NO_SPREADSHEET_ID' };
  }

  console.log(`[Google Sheets Sync] Connecting to spreadsheet ID: ${spreadsheetId}...`);

  // 1. Sync Products (Stationery & Gadgets)
  try {
    const productsCsvUrl = `https://docs.google.com/spreadsheets/d/${spreadsheetId}/gviz/tq?tqx=out:csv&sheet=${encodeURIComponent(productsSheetName)}`;
    console.log(`[Google Sheets Sync] Fetching "${productsSheetName}" CSV...`);
    const res = await fetch(productsCsvUrl);
    if (!res.ok) throw new Error(`HTTP ${res.status} ${res.statusText}`);
    const csvText = await res.text();
    const rows = parseCSV(csvText);

    if (rows.length > 0) {
      const transformedProducts = rows.map((r, idx) => ({
        id: parseInt(r.id, 10) || idx + 1,
        title: r.title || 'Stationery Item',
        category: r.category || 'stationery',
        tag: r.tag || 'Tk 99 Special',
        price: parseFloat(r.price) || 99,
        originalPrice: parseFloat(r.originalprice || r.originalPrice) || 120,
        icon: r.icon || 'fa-box',
        desc: r.desc || r.description || '',
        badgeColor: r.badgecolor || 'border border-sky-400/40 bg-sky-500/20 text-sky-200',
      }));

      const productsDataFile = `// Auto-generated by scripts/sync-google-sheets.js from Google Sheets\n// Last synced: ${new Date().toISOString()}\n\nexport const productsData = ${JSON.stringify(transformedProducts, null, 2)};\n`;
      const targetPath = path.join(projectRoot, 'src', 'data', 'productsData.js');
      await fs.writeFile(targetPath, productsDataFile, 'utf-8');
      console.log(`[Google Sheets Sync] Successfully updated ${transformedProducts.length} products in src/data/productsData.js`);
    }
  } catch (err) {
    console.error('[Google Sheets Sync] Products sync error:', err.message);
  }

  // 2. Sync Services (Printing & Photo rates)
  try {
    const servicesCsvUrl = `https://docs.google.com/spreadsheets/d/${spreadsheetId}/gviz/tq?tqx=out:csv&sheet=${encodeURIComponent(servicesSheetName)}`;
    console.log(`[Google Sheets Sync] Fetching "${servicesSheetName}" CSV...`);
    const res = await fetch(servicesCsvUrl);
    if (!res.ok) throw new Error(`HTTP ${res.status} ${res.statusText}`);
    const csvText = await res.text();
    const rows = parseCSV(csvText);

    if (rows.length > 0) {
      const transformedServices = rows.map((r, idx) => ({
        id: r.id || `service-${idx + 1}`,
        code: r.code || `0${idx + 1}`,
        title: r.title || 'Service Title',
        description: r.description || '',
        category: r.category || 'GENERAL_SERVICE',
        items: r.items ? r.items.split(';').map((s) => s.trim()) : [],
        whatsappMsg: r.whatsappmsg || 'Hello Shafayat! I would like to inquire about your services.',
        badge: r.badge || 'Available Now',
      }));

      const servicesDataFile = `// Auto-generated by scripts/sync-google-sheets.js from Google Sheets\n// Last synced: ${new Date().toISOString()}\n\nexport const servicesData = ${JSON.stringify(transformedServices, null, 2)};\n`;
      const targetPath = path.join(projectRoot, 'src', 'data', 'servicesData.js');
      await fs.writeFile(targetPath, servicesDataFile, 'utf-8');
      console.log(`[Google Sheets Sync] Successfully updated ${transformedServices.length} services in src/data/servicesData.js`);
    }
  } catch (err) {
    console.error('[Google Sheets Sync] Services sync error:', err.message);
  }

  return { synced: true };
}

// Execute when run directly
if (process.argv[1] === fileURLToPath(import.meta.url)) {
  syncGoogleSheets().catch((err) => {
    console.error('[Google Sheets Sync] Error:', err);
    process.exit(1);
  });
}
